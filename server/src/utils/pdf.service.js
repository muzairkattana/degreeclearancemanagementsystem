import PDFDocument from 'pdfkit';

/**
 * Generate an official University Degree Clearance Certificate PDF stream
 * @param {Object} clearance - The clearance object with student and department reviews
 * @param {Object} res - Express response stream
 */
export const buildClearancePdf = (clearance, res) => {
  const doc = new PDFDocument({ size: 'A4', margin: 40 });

  // Stream PDF directly into response
  doc.pipe(res);

  const student = clearance.student || {};
  const completedDate = clearance.completed_at
    ? new Date(clearance.completed_at).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })
    : new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' });

  // Outer decorative border
  doc.rect(20, 20, 555, 802).lineWidth(2).strokeColor('#00173b').stroke();
  doc.rect(25, 25, 545, 792).lineWidth(0.8).strokeColor('#c59b27').stroke();

  // Header Title
  doc.moveDown(1);
  doc.fontSize(19).font('Helvetica-Bold').fillColor('#00173b').text('UNIVERSITY OF ENGINEERING & TECHNOLOGY, MARDAN', { align: 'center' });
  doc.fontSize(11).font('Helvetica').fillColor('#475569').text('OFFICE OF THE CONTROLLER OF EXAMINATIONS', { align: 'center' });
  doc.moveDown(0.4);
  doc.fontSize(10).fillColor('#64748b').text('Charsadda Road, Mardan, Khyber Pakhtunkhwa, Pakistan', { align: 'center' });
  
  doc.moveDown(0.8);
  doc.fontSize(14).font('Helvetica-Bold').fillColor('#c59b27').text('OFFICIAL DEGREE CLEARANCE CERTIFICATE', { align: 'center' });
  doc.fontSize(9).font('Helvetica').fillColor('#64748b').text(`Certificate ID: UETM-CLR-${clearance.clearance_id}-${new Date().getFullYear()}`, { align: 'center' });

  // Divider
  doc.moveDown(0.8);
  doc.strokeColor('#e2e8f0').lineWidth(1).moveTo(40, doc.y).lineTo(555, doc.y).stroke();
  doc.moveDown(1);

  // Student Particulars Box
  const boxTop = doc.y;
  doc.rect(40, boxTop, 515, 85).fillAndStroke('#f8fafc', '#cbd5e1');
  doc.fillColor('#00173b');

  doc.font('Helvetica-Bold').fontSize(10).text('Student Name:', 55, boxTop + 15);
  doc.font('Helvetica').text(student.full_name || 'N/A', 160, boxTop + 15);

  doc.font('Helvetica-Bold').text('Registration No:', 320, boxTop + 15);
  doc.font('Helvetica').text(student.registration_no || 'N/A', 430, boxTop + 15);

  doc.font('Helvetica-Bold').text('Academic Program:', 55, boxTop + 35);
  doc.font('Helvetica').text(student.program?.name || 'BSc Computer Software Engineering', 160, boxTop + 35);

  doc.font('Helvetica-Bold').text('CNIC / National ID:', 320, boxTop + 35);
  doc.font('Helvetica').text(student.cnic || '15603-XXXXXXX-X', 430, boxTop + 35);

  doc.font('Helvetica-Bold').text('Clearance Status:', 55, boxTop + 55);
  doc.font('Helvetica-Bold').fillColor('#047857').text('COMPLETED & CLEARED', 160, boxTop + 55);

  doc.font('Helvetica-Bold').fillColor('#00173b').text('Issue Date:', 320, boxTop + 55);
  doc.font('Helvetica').text(completedDate, 430, boxTop + 55);

  doc.y = boxTop + 105;

  // Department Verification Statement
  doc.font('Helvetica').fontSize(10).fillColor('#334155').text(
    'This is to certify that the graduate above has satisfied all university requirements and holds NO OUTSTANDING DUES OR LIABILITIES with the respective academic and administrative departments of the university:',
    { align: 'justify', lineGap: 3 }
  );

  doc.moveDown(0.8);

  // Table of 8 Departments
  const tableTop = doc.y;
  doc.rect(40, tableTop, 515, 20).fillAndStroke('#00173b', '#00173b');
  doc.font('Helvetica-Bold').fontSize(9).fillColor('#ffffff');
  doc.text('Sr.', 48, tableTop + 6);
  doc.text('Department / Section', 75, tableTop + 6);
  doc.text('Verification Status', 260, tableTop + 6);
  doc.text('Officer Remarks', 380, tableTop + 6);

  let currentY = tableTop + 20;
  const reviews = clearance.departmentReviews || [];

  reviews.forEach((rev, index) => {
    const isEven = index % 2 === 0;
    doc.rect(40, currentY, 515, 22).fillAndStroke(isEven ? '#ffffff' : '#f8fafc', '#e2e8f0');

    doc.font('Helvetica').fontSize(9).fillColor('#00173b').text(String(index + 1), 48, currentY + 6);
    doc.text(rev.department?.name || `Department ${rev.department_id}`, 75, currentY + 6);

    const isApproved = rev.status === 'approved';
    doc.font('Helvetica-Bold').fillColor(isApproved ? '#047857' : '#b91c1c')
      .text(isApproved ? 'VERIFIED / CLEARED' : rev.status.toUpperCase(), 260, currentY + 6);

    doc.font('Helvetica').fillColor('#475569')
      .text(rev.remarks ? (rev.remarks.length > 28 ? rev.remarks.slice(0, 25) + '...' : rev.remarks) : 'Cleared', 380, currentY + 6);

    currentY += 22;
  });

  doc.y = currentY + 25;

  // Verification & Signatures section
  doc.font('Helvetica-Oblique').fontSize(8.5).fillColor('#64748b').text(
    'Note: This is a system-verified electronic clearance document generated by the UET Mardan Academic ERP Portal. It is accepted by the Examination Branch for official Degree / Provisional Certificate Issuance.',
    { align: 'center' }
  );

  doc.moveDown(3);

  // Signatures
  const sigY = doc.y;
  doc.strokeColor('#94a3b8').lineWidth(1);
  
  doc.moveTo(60, sigY).lineTo(200, sigY).stroke();
  doc.moveTo(350, sigY).lineTo(500, sigY).stroke();

  doc.font('Helvetica-Bold').fontSize(9).fillColor('#00173b');
  doc.text('Assistant Controller (Exams)', 65, sigY + 6);
  doc.text('Controller of Examinations', 360, sigY + 6);

  doc.font('Helvetica').fontSize(8).fillColor('#64748b');
  doc.text('UET Mardan Verification Cell', 72, sigY + 18);
  doc.text('Official Seal & Sign-off', 385, sigY + 18);

  // Finalize PDF
  doc.end();
};
